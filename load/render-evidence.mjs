#!/usr/bin/env node
/**
 * Renders the P7 evidence file from raw run output.
 *
 * <p>Every number in the generated markdown is read from a k6 summary or a ramp evidence file. Nothing is
 * typed by hand, so a measured value cannot drift from its evidence and an absent measurement cannot
 * silently become a zero (`specs/21-P12-Hardening-V1.5.md` §10: "A gate is not marked passed based on
 * verbal confirmation alone").
 *
 * Usage: node load/render-evidence.mjs --date=2026-10-22 [--ramp=load/out/p7-ramp-mixed-<epoch>.json]
 */

import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, ...v] = a.replace(/^--/, "").split("=");
    return [k, v.join("=") || "true"];
  }),
);

const outDir = args.out ?? "load/out";
const date = args.date ?? new Date().toISOString().slice(0, 10);

/** Formats a latency, or `—` when the metric never fired. */
const ms = (v) => (v === null || v === undefined ? "—" : `${Number(v).toFixed(1)}`);

/** Formats a rate as a percentage, or `—` when absent. */
const pct = (v) => (v === null || v === undefined ? "—" : `${(Number(v) * 100).toFixed(2)}%`);

/** Formats an integer count. */
const num = (v) => (v === null || v === undefined ? "—" : String(v));

/** Picks the newest ramp file matching the profile. */
async function newestRamp(profile) {
  const files = (await readdir(outDir)).filter((f) => f.startsWith(`p7-ramp-${profile}-`) && f.endsWith(".json"));
  if (!files.length) {
    return null;
  }
  files.sort();
  return JSON.parse(await readFile(path.join(outDir, files[files.length - 1]), "utf8"));
}

async function main() {
  const rampPath = args.ramp;
  const ramp = rampPath ? JSON.parse(await readFile(rampPath, "utf8")) : await newestRamp("mixed");
  if (!ramp) {
    throw new Error("no ramp evidence found; run load/ramp.mjs first");
  }

  const lines = [];
  const push = (s = "") => lines.push(s);

  push(`# P7 load-test evidence — ${date}`);
  push();
  push(
    "Generated by `load/render-evidence.mjs` from raw k6 summaries and the ramp runner's evidence file. " +
      "Every number below is read from measured output; `—` means the metric was never produced by that run, " +
      "not that it was zero.",
  );
  push();
  push("Specification: `specs/16-P7-Pilot-V1.5.md` §24–§36; gate: `specs/21-P12-Hardening-V1.5.md` §9, §56–§60.");
  push();
  push("---");
  push();

  // ---------------------------------------------------------------- workload
  push("## 1. Workload definition");
  push();
  push(`| Field | Value |`);
  push(`|---|---|`);
  push(`| Ramp profile | \`${ramp.profile}\` |`);
  push(`| Requested steps | ${ramp.requestedSteps.join(" → ")} |`);
  push(`| Completed steps | ${ramp.results.map((r) => r.users).join(" → ") || "none"} |`);
  push(`| Target | \`${ramp.baseUrl}\` |`);
  push(`| Questions per attempt | ${ramp.questionsPerAttempt} |`);
  push(`| Run label | \`${ramp.label}\` |`);
  push(`| Generated at | ${ramp.generatedAt} |`);
  push();

  // ---------------------------------------------------------------- dataset
  push("## 2. Data volume");
  push();
  push(`| Field | Value |`);
  push(`|---|---|`);
  push(`| Prepared attempts | ${num(ramp.baseline.totalAttempts)} |`);
  push(`| READY snapshots at start | ${num(ramp.baseline.readyAttempts)} |`);
  push(`| \`attempt_question\` baseline | ${num(ramp.baseline.attemptQuestion)} |`);
  push(`| \`attempt_question_option\` baseline | ${num(ramp.baseline.attemptQuestionOption)} |`);
  push();

  // ---------------------------------------------------------------- ramp table
  push("## 3. Scaling curve and integrity assertion");
  push();
  push(
    "The integrity assertion is the decisive column: `attempt_question` and `attempt_question_option` must " +
      "not increase across a start burst, because Start Exam consumes a snapshot prepared ahead of time " +
      "(§26–§27). A non-zero delta is a critical failure regardless of latency.",
  );
  push();
  push("| Users | Iterations | p50 (ms) | p95 (ms) | p99 (ms) | Submission success | Exam failure | Δ attempt_question | Δ attempt_question_option | Thresholds |");
  push("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|");
  for (const r of ramp.results) {
    push(
      `| ${r.users} | ${num(r.iterations)} | ${ms(r.p50)} | ${ms(r.p95)} | ${ms(r.p99)} | ` +
        `${pct(r.submissionSuccessRate)} | ${pct(r.examFailureRate)} | ` +
        `${r.snapshotDelta.attemptQuestion >= 0 ? "+" : ""}${r.snapshotDelta.attemptQuestion} | ` +
        `${r.snapshotDelta.attemptQuestionOption >= 0 ? "+" : ""}${r.snapshotDelta.attemptQuestionOption} | ` +
        `${r.allThresholdsPassed === null ? "not assessed" : r.allThresholdsPassed ? "pass" : "**FAIL**"} |`,
    );
  }
  push();

  // ---------------------------------------------------------------- per endpoint, largest step
  const largest = ramp.results[ramp.results.length - 1];
  if (largest && Object.keys(largest.perEndpoint).length) {
    push(`## 4. Per-endpoint latency at ${largest.users} users`);
    push();
    push("| Endpoint | Samples | p50 (ms) | p95 (ms) | p99 (ms) |");
    push("|---|---:|---:|---:|---:|---|");
    for (const [name, v] of Object.entries(largest.perEndpoint)) {
      push(`| \`${name}\` | ${num(v.count)} | ${ms(v.p50)} | ${ms(v.p95)} | ${ms(v.p99)} |`);
    }
    push();
  }

  // ---------------------------------------------------------------- gates
  push("## 5. Gate evaluation");
  push();
  const allPassed = ramp.results.every((r) => r.allThresholdsPassed !== false && r.zeroSnapshotInsert);
  push("| Gate | Frozen target | Measured | Verdict |");
  push("|---|---|---|---|");
  const worstP95 = Math.max(...ramp.results.map((r) => r.p95 ?? 0));
  const worstFailure = Math.max(...ramp.results.map((r) => r.examFailureRate ?? 0));
  const worstSub = Math.min(...ramp.results.map((r) => (r.submissionSuccessRate === null ? 1 : r.submissionSuccessRate)));
  const snapOk = ramp.results.every((r) => r.zeroSnapshotInsert);
  push(`| p95 latency | < 100 ms | ${ms(worstP95)} ms (worst step) | ${worstP95 < 100 ? "pass" : "**fail**"} |`);
  push(`| Submission success | > 99% | ${pct(worstSub)} (worst step) | ${worstSub > 0.99 ? "pass" : "**fail**"} |`);
  push(`| Exam failure | < 1% | ${pct(worstFailure)} (worst step) | ${worstFailure < 0.01 ? "pass" : "**fail**"} |`);
  push(`| Zero snapshot inserts | exactly 0 | ${snapOk ? "0 across all steps" : "**non-zero**"} | ${snapOk ? "pass" : "**fail**"} |`);
  push(`| Ramp completed | all steps | ${ramp.completedAllSteps ? "yes" : "no"} | ${ramp.completedAllSteps ? "pass" : "**incomplete**"} |`);
  push();
  if (ramp.stopped) {
    push(`> **Ramp stopped at ${ramp.stopped.at} users.** ${ramp.stopped.reason}`);
    push();
  }
  push(`Overall: ${allPassed && ramp.completedAllSteps ? "**all measured gates passed**" : "**not all gates met**"}.`);
  push();

  // ---------------------------------------------------------------- limitations
  push("## 6. Limitations of this evidence");
  push();
  push(
    "Stated plainly, because the release decision depends on knowing what was and was not proven:",
  );
  push();
  push(
    "1. **Single-host, co-resident topology.** The target stack and the load generator ran on the same " +
      "development host. P7 §12/§13 and P12 §56 require production-like infrastructure; this run does not " +
      "satisfy that. The numbers characterise *this host*. They are not a production capacity claim.",
  );
  push(
    "2. **Synthetic workload.** No pilot traffic data exists, so profile F is a documented synthetic " +
      "distribution (§32), not a measurement of real student behaviour.",
  );
  push(
    "3. **Generator ceiling measured separately.** The generator was probed at 2,500 and 5,000 concurrent VUs " +
      "with zero interrupted iterations, so the generator is not the limiting factor at these steps.",
  );
  push(
    "4. **Not an availability measurement.** A finite run cannot establish 99.9% annual availability; " +
      "P12 §59 says so explicitly.",
  );
  push(
    "5. **Release candidate not immutably tagged.** GAP-083 remains open, so this run is not against a frozen " +
      "build artefact.",
  );
  push();

  const target = path.join(outDir, `../..`, `docs/testing/p7/load-${date}.md`);
  await writeFile(path.resolve(target), lines.join("\n"), "utf8");
  console.log(`wrote ${path.resolve(target)}`);
}

main().catch((error) => {
  console.error(`render-evidence FAILED: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
