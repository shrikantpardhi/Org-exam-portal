package com.company.exam.reporting.renderer;

import com.company.exam.reporting.projection.ReportProjection;
import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.springframework.stereotype.Component;

/**
 * PDF rendering ({@code specs/22-P13-Reporting-V1.5.md §19}).
 *
 * <p>Emits a valid PDF 1.4 document with a title, report period, applied filters, generation
 * timestamp, summary metrics, data tables, and page numbers. It is implemented without a third-party
 * library: the writer emits the object graph, content streams, xref table, and trailer directly, so
 * the platform adds no PDF dependency and the output is deterministic and testable.
 *
 * <p>Sensitive internal identifiers are only present when a report's own columns include them, and
 * no filesystem path, credential, or storage reference ever reaches the document.
 */
@Component
public class PdfRenderer {

    private static final int PAGE_WIDTH = 595;
    private static final int PAGE_HEIGHT = 842;
    private static final int MARGIN = 48;
    private static final int LINE_HEIGHT = 13;
    private static final int MAX_CHARS_PER_LINE = 110;

    public byte[] render(ReportProjection projection) {
        List<String> lines = layout(projection);
        List<String> pages = paginate(lines);
        return assemble(pages);
    }

    /** Builds the document text: header block, summary metrics, then the table (§19). */
    private List<String> layout(ReportProjection projection) {
        List<String> lines = new ArrayList<>();
        lines.add(projection.title() == null ? "Report" : projection.title());
        lines.add("");
        if (projection.period() != null && !projection.period().isBlank()) {
            lines.add("Period: " + projection.period());
        }
        if (projection.generatedAt() != null) {
            lines.add("Generated: " + DateTimeFormatter.ISO_OFFSET_DATE_TIME
                    .withZone(ZoneOffset.UTC).format(projection.generatedAt()));
        }
        if (projection.generatedBy() != null) {
            lines.add("Generated by: " + projection.generatedBy());
        }
        if (projection.appliedFilters() != null && !projection.appliedFilters().isEmpty()) {
            lines.add("Filters: " + projection.appliedFilters());
        }
        lines.add("Rows: " + projection.rowCount());
        if (projection.freshnessNote() != null && !projection.freshnessNote().isBlank()) {
            lines.add("Note: " + projection.freshnessNote());
        }
        lines.add("");

        if (projection.metrics() != null && !projection.metrics().isEmpty()) {
            lines.add("Summary");
            for (ReportProjection.SummaryMetric metric : projection.metrics()) {
                // An executive metric always prints its definition (§70).
                String definition = metric.definition() == null ? "" : "  (" + metric.definition() + ")";
                lines.add("  " + metric.name() + ": " + metric.value() + definition);
            }
            lines.add("");
        }

        if (projection.columns() != null && !projection.columns().isEmpty()) {
            List<String> header = projection.columns().stream().map(ReportProjection.Column::label).toList();
            lines.add(String.join(" | ", header));
            lines.add("-".repeat(Math.min(MAX_CHARS_PER_LINE, Math.max(10, String.join(" | ", header).length()))));
            for (Map<String, String> row : projection.rows()) {
                List<String> cells = new ArrayList<>();
                for (ReportProjection.Column column : projection.columns()) {
                    String value = row.get(column.key());
                    cells.add(value == null ? "" : value);
                }
                lines.add(String.join(" | ", cells));
            }
        } else if (projection.rowCount() == 0) {
            lines.add("No matching data for the requested filters.");
        }
        return lines;
    }

    private List<String> paginate(List<String> lines) {
        int linesPerPage = (PAGE_HEIGHT - (2 * MARGIN)) / LINE_HEIGHT - 2;
        List<String> pages = new ArrayList<>();
        StringBuilder page = new StringBuilder();
        int used = 0;
        for (String line : lines) {
            for (String wrapped : wrap(line)) {
                if (used == linesPerPage) {
                    pages.add(page.toString());
                    page.setLength(0);
                    used = 0;
                }
                page.append(wrapped).append('\n');
                used++;
            }
        }
        pages.add(page.toString());
        return pages;
    }

    private List<String> wrap(String line) {
        if (line.length() <= MAX_CHARS_PER_LINE) {
            return List.of(line);
        }
        List<String> wrapped = new ArrayList<>();
        int index = 0;
        while (index < line.length()) {
            wrapped.add(line.substring(index, Math.min(index + MAX_CHARS_PER_LINE, line.length())));
            index += MAX_CHARS_PER_LINE;
        }
        return wrapped;
    }

    /** Assembles the object graph, xref table, and trailer into a valid PDF byte sequence. */
    private byte[] assemble(List<String> pages) {
        int pageCount = pages.size();
        List<byte[]> objects = new ArrayList<>();
        // Object numbers: 1 catalog, 2 pages, 3 font, then per page a content stream and a page object.
        objects.add(ascii("<< /Type /Catalog /Pages 2 0 R >>"));
        StringBuilder kids = new StringBuilder();
        for (int index = 0; index < pageCount; index++) {
            kids.append(4 + (index * 2)).append(" 0 R ");
        }
        objects.add(ascii("<< /Type /Pages /Kids [" + kids.toString().trim() + "] /Count " + pageCount + " >>"));
        objects.add(ascii("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"));
        for (int index = 0; index < pageCount; index++) {
            byte[] stream = contentStream(pages.get(index), index + 1, pageCount);
            ByteArrayOutputStream contentObject = new ByteArrayOutputStream();
            contentObject.writeBytes(ascii("<< /Length " + stream.length + " >>\nstream\n"));
            contentObject.writeBytes(stream);
            contentObject.writeBytes(ascii("\nendstream"));
            objects.add(contentObject.toByteArray());
            objects.add(ascii("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 " + PAGE_WIDTH + " " + PAGE_HEIGHT
                    + "] /Resources << /Font << /F1 3 0 R >> >> /Contents " + (4 + (index * 2)) + " 0 R >>"));
        }

        ByteArrayOutputStream pdf = new ByteArrayOutputStream();
        pdf.writeBytes(ascii("%PDF-1.4\n"));
        List<Integer> offsets = new ArrayList<>();
        for (int index = 0; index < objects.size(); index++) {
            offsets.add(pdf.size());
            pdf.writeBytes(ascii((index + 1) + " 0 obj\n"));
            pdf.writeBytes(objects.get(index));
            pdf.writeBytes(ascii("\nendobj\n"));
        }
        int xrefOffset = pdf.size();
        StringBuilder xref = new StringBuilder();
        xref.append("xref\n0 ").append(objects.size() + 1).append('\n');
        xref.append("0000000000 65535 f \n");
        for (Integer offset : offsets) {
            xref.append(String.format("%010d 00000 n \n", offset));
        }
        pdf.writeBytes(ascii(xref.toString()));
        pdf.writeBytes(ascii("trailer\n<< /Size " + (objects.size() + 1) + " /Root 1 0 R >>\nstartxref\n"
                + xrefOffset + "\n%%EOF\n"));
        return pdf.toByteArray();
    }

    private byte[] contentStream(String pageText, int pageNumber, int pageCount) {
        StringBuilder content = new StringBuilder();
        content.append("BT\n/F1 10 Tf\n");
        int y = PAGE_HEIGHT - MARGIN;
        for (String line : pageText.split("\n", -1)) {
            if (!line.isEmpty()) {
                content.append("1 0 0 1 ").append(MARGIN).append(' ').append(y).append(" Tm (")
                        .append(escapeText(line)).append(") Tj\n");
            }
            y -= LINE_HEIGHT;
        }
        content.append("1 0 0 1 ").append(MARGIN).append(' ').append(MARGIN - 16).append(" Tm (Page ")
                .append(pageNumber).append(" of ").append(pageCount).append(") Tj\n");
        content.append("ET\n");
        return ascii(content.toString());
    }

    /** Escapes PDF string delimiters and drops characters Helvetica cannot represent. */
    private String escapeText(String value) {
        StringBuilder escaped = new StringBuilder();
        for (char character : value.toCharArray()) {
            switch (character) {
                case '(' -> escaped.append("\\(");
                case ')' -> escaped.append("\\)");
                case '\\' -> escaped.append("\\\\");
                default -> escaped.append(character < 32 || character > 126 ? '?' : character);
            }
        }
        return escaped.toString();
    }

    private byte[] ascii(String value) {
        return value.getBytes(StandardCharsets.ISO_8859_1);
    }
}
